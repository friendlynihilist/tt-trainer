// ── Misure ──────────────────────────────────────────────────────────────────

/** n tentativi, si contano quelli buoni. Con `parts` la serie ha più conteggi (es. dritto e rovescio). */
const su = (n, what = '', parts = null) => ({ type: 'su', n, what, ...(parts ? { parts } : {}) });
/** Quante di fila. `unit`: colpi (solo i tuoi), scambi (di tutti e due), cicli, sequenze, difese. */
const fila = (unit = 'colpi') => ({ type: 'fila', unit });
/** Quanti in 30 secondi. */
const tempo = (unit = 'colpi', seconds = 30) => ({ type: 'tempo', unit, seconds });
/** Un conteggio per seduta. */
const conta = (what) => ({ type: 'conta', what });

/** Quante prove valgono in una seduta per ogni tipo di misura (regole 2, 3 e 4). */
export const TRIES_PER_DAY = { su: 1, conta: 1, fila: 3, tempo: 3 };

